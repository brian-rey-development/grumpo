//! Rust constants the interface reads, written beside the ts-rs types so the two cannot drift.
//!
//! `scripts/gen-bindings.sh` regenerates them with the types, and `scripts/check.sh` fails when
//! the files in `app/src/ipc/generated` are not what this code writes.

use std::fmt::Write as _;
use std::fs;
use std::io;

use crate::time::units;
use crate::{
    CONFIRM_WINDOW_MINUTES, COOLDOWN_STEPS_MINUTES, MAX_APPS, MAX_DOMAIN_LEN, MAX_LABEL_LEN,
    MAX_LIMITS, MAX_LIMIT_MINUTES, MAX_SITES, MAX_WINDOWS, MIN_LIMIT_MINUTES,
    UNLOCK_DURATIONS_MINUTES,
};

const HEADER: &str = "// This file was generated by focus-core. Do not edit this file manually.\n";

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Value {
    Number(i64),
    Numbers(Vec<i64>),
    Strings(Vec<&'static str>),
}

/// One exported TypeScript constant, named like its Rust source.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Constant {
    name: &'static str,
    doc: &'static str,
    value: Value,
}

impl Constant {
    pub fn number(name: &'static str, doc: &'static str, value: impl Into<i64>) -> Self {
        Self {
            name,
            doc,
            value: Value::Number(value.into()),
        }
    }

    pub fn numbers<T: Copy + Into<i64>>(
        name: &'static str,
        doc: &'static str,
        values: &[T],
    ) -> Self {
        Self {
            name,
            doc,
            value: Value::Numbers(values.iter().map(|&value| value.into()).collect()),
        }
    }

    pub fn strings(name: &'static str, doc: &'static str, values: &[&'static str]) -> Self {
        Self {
            name,
            doc,
            value: Value::Strings(values.to_vec()),
        }
    }

    fn render(&self) -> String {
        let value = match &self.value {
            Value::Number(number) => number.to_string(),
            Value::Numbers(numbers) => {
                let items: Vec<String> = numbers.iter().map(ToString::to_string).collect();
                format!("[{}] as const", items.join(", "))
            }
            Value::Strings(strings) => {
                let items: Vec<String> = strings.iter().map(|text| format!("{text:?}")).collect();
                format!("[{}] as const", items.join(", "))
            }
        };
        format!(
            "/** {} */\nexport const {} = {};\n",
            self.doc, self.name, value
        )
    }
}

/// The module text for `constants`, in the order given.
pub fn render(constants: &[Constant]) -> String {
    let mut text = String::from(HEADER);
    for constant in constants {
        let _ = write!(text, "\n{}", constant.render());
    }
    text
}

/// Writes `constants` to `file` in the directory ts-rs exports its types to.
///
/// Any crate with constants for the interface calls this from a test with the `ts` feature,
/// and gives its own file name, so the generated directory stays the single place to look.
pub fn export(file: &str, constants: &[Constant]) -> io::Result<()> {
    let directory = ts_rs::Config::from_env().out_dir().to_path_buf();
    fs::create_dir_all(&directory)?;
    fs::write(directory.join(file), render(constants))
}

/// The constants of this crate that the interface needs: rule caps, limit bounds, the unlock
/// timings, the domain lengths and the unit conversions.
pub fn core_constants() -> Vec<Constant> {
    [
        rule_limits(),
        unlock_timings(),
        domain_lengths(),
        units_of_time(),
    ]
    .concat()
}

